#Arithmetic Operators - simple calculation
x = 10
y = 5

print(x + y)
print(x - y)
print(x * y)
print(x / y)
print(x % y)

#comparison operators - compare values return a boolean
num1 = 50
num2 = 67

print(num1 <num2)
print(num1 > num2)
print(num1 <= num2)
print(num1 >= num2)
print(num1 == num2)#equal to
print(num1 != num2)# not equal to


#Assignment Operators - Assign/store values in variables
number = 10
print(number)

#operator precedence - order in which operation get executed
number += 2
print(number)

# Logical operators - and, or, not
print(100 == 30 and 60 < 30)
print(100 == 30 or 60 < 30)
print( not(100 == 30 and 60 < 30))
